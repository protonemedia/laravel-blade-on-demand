## Laravel Blade On Demand

- `protonemedia/laravel-blade-on-demand` renders Blade template strings in memory without writing view files to disk, with support for Markdown mail rendering.
- Always activate the `laravel-blade-on-demand-development` skill when working with in-memory Blade rendering, Markdown mail previews, or any code that uses the `BladeOnDemand` facade.
